const CAP = { 0: 2, 1: 6, 2: 10, 3: 14 };
function shellsOf(Z) {
  const sub = {}; let left = Z;
  for (const [n, l] of ORDER) {
    if (left <= 0) break;
    const take = Math.min(left, CAP[l]);
    sub[n + ',' + l] = take; left -= take;
  }
  const shells = {};
  for (const k in sub) {
    const n = +k.split(',')[0];
    shells[n] = (shells[n] || 0) + sub[k];
  }
  return Object.keys(shells).sort((a, b) => a - b).map(n => shells[n]);
}
